    public static string Get(string key, string fallback = null)
    {
        if (string.IsNullOrEmpty(key))
            return fallback ?? string.Empty;

        try
        {
            string value = new LocalizedString(TableName, key).GetLocalizedString();
            if (!string.IsNullOrEmpty(value) && value != key)
                return value;
        }
        catch (Exception)
        {
        }

        return fallback ?? key;
    }

    public static string GetByEnglish(string english, string fallback = null)
    {
        if (string.IsNullOrEmpty(english))
            return fallback ?? english;

        if (GermanAliases.TryGetValue(english, out string alias))
            english = alias;

        var map = GetEnglishMap();
        if (map != null && map.TryGetValue(english, out string key))
            return Get(key, fallback ?? english);

        return fallback ?? english;
    }

    public static string Format(string key, string fallback, params object[] args)
    {
        string text = Get(key, fallback);
        try
        {
            return string.Format(text, args);
        }
        catch (FormatException)
        {
            return text;
        }
    }

    private static Dictionary<string, string> GetEnglishMap()
    {
        return EnglishToKeyMap;
    }
